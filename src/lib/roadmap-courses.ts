export type CourseTopic = { title: string; summary: string; minutes: number; lecture?: string; practice?: string; codeCell?: { language: "java"; code: string } };

export function topicLearningMaterial(topic: Pick<CourseTopic, "title" | "summary" | "lecture" | "practice">, track: CourseTrack = "general") {
  const curated = courseMaterials[track]?.[topic.title];
  const expansion = lectureExpansions[track]?.[topic.title];
  const readingNote = courseReadingNote(track, topic.title);
  if (topic.lecture !== undefined || topic.practice !== undefined) return {
    lecture: topic.lecture ?? `${curated?.explanation ?? topic.summary}${expansion ? `\n\n${expansion}` : ""}${readingNote ? `\n\n${readingNote}` : ""}${curated ? `\n\n${curated.example}` : ""}`,
    practice: topic.practice ?? curated?.practice ?? `ЗАДАНИЕ\nПримените «${topic.title}» к одному сценарию из проекта. Опишите решение и проверьте обычный и граничный случай.`,
  };
  if (curated) return {
    lecture: `${curated.explanation}${expansion ? `\n\n${expansion}` : ""}${readingNote ? `\n\n${readingNote}` : ""}\n\n${curated.example}`,
    practice: curated.practice,
  };
  return {
    lecture: topic.lecture ?? `${topic.summary}\n\nПРИМЕР\nРассмотрите, как «${topic.title}» применяется в вашем проекте. Запишите входные данные, результат и один крайний случай.`,
    practice: topic.practice ?? `ЗАДАНИЕ\nПримените «${topic.title}» к одному сценарию из проекта. Опишите решение и проверьте его на обычном примере и одном граничном случае.`,
  };
}

